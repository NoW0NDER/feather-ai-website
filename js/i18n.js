// i18n Engine
const i18n = {
  currentLang: 'en',

  init() {
    const saved = localStorage.getItem('feather-ai-lang');
    if (saved && translations[saved]) {
      this.currentLang = saved;
    }
    this.apply();
    this.updateLangBtn();
    this.bindEvents();
  },

  setLang(lang) {
    if (!translations[lang]) return;
    this.currentLang = lang;
    localStorage.setItem('feather-ai-lang', lang);
    document.documentElement.setAttribute('data-lang', lang);
    this.apply();
    this.updateLangBtn();
  },

  apply() {
    const t = translations[this.currentLang];
    document.querySelectorAll('[data-i18n]').forEach(el => {
      const key = el.getAttribute('data-i18n');
      if (t[key]) {
        el.innerHTML = t[key];
      }
    });
    // Update html lang attribute
    const langMap = { 'zh-TW': 'zh-Hant', 'zh-CN': 'zh-Hans', ja: 'ja', fr: 'fr', de: 'de', en: 'en' };
    document.documentElement.lang = langMap[this.currentLang] || this.currentLang;
  },

  updateLangBtn() {
    const labelMap = { en: 'EN', 'zh-TW': '繁', 'zh-CN': '简', ja: '日', fr: 'FR', de: 'DE' };
    const btn = document.getElementById('langBtn');
    if (btn) {
      btn.querySelector('.lang-label').textContent = labelMap[this.currentLang] || this.currentLang.toUpperCase();
    }
    // Mark active in dropdown
    document.querySelectorAll('#langDropdown button').forEach(b => {
      b.classList.toggle('active', b.dataset.lang === this.currentLang);
    });
  },

  bindEvents() {
    const switcher = document.getElementById('langSwitcher');
    const btn = document.getElementById('langBtn');
    const dropdown = document.getElementById('langDropdown');

    btn.addEventListener('click', (e) => {
      e.stopPropagation();
      switcher.classList.toggle('open');
    });

    dropdown.addEventListener('click', (e) => {
      const button = e.target.closest('button[data-lang]');
      if (button) {
        this.setLang(button.dataset.lang);
        switcher.classList.remove('open');
      }
    });

    document.addEventListener('click', () => {
      switcher.classList.remove('open');
    });
  }
};
